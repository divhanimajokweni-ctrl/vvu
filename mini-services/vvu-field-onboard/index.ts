// ─── Receipts (SHA-256 hash chain, WORM-style — kept from the rail) ─────────

function sha256(s: string): string {
  return createHash('sha256').update(s, 'utf8').digest('hex');
}

function canonical(r: Omit<Receipt, 'hash'>): string {
  // stable field order — the hash covers everything except itself
  return JSON.stringify([r.seq, r.ts, r.actor, r.op, r.target, r.ok, r.sha256, r.prevHash]);
}

function appendReceipt(actor: string, op: string, target: string, ok: boolean, payload: unknown): Receipt {
  const prev = receipts.length ? receipts[receipts.length - 1].hash : GENESIS_PREV;
  const body = {
    seq: receipts.length + 1,
    ts: new Date().toISOString(),
    actor,
    op,
    target: target.slice(0, 256),
    ok,
    sha256: sha256(typeof payload === 'string' ? payload : JSON.stringify(payload ?? null)),
    prevHash: prev,
  } satisfies Omit<Receipt, 'hash'>;
  const receipt: Receipt = { ...body, hash: sha256(canonical(body)) };
  receipts.push(receipt);
  try {
    writeFileSync(RECEIPTS_FILE, JSON.stringify({ genesis: GENESIS_PREV, receipts }, null, 1));
  } catch {
    /* persistence failure is non-fatal — chain stays in memory */
  }
  return receipt;
}

function verifyChain(chain: Receipt[]): { valid: boolean; checked: number; firstBadIndex: number; root: string; merkleRoot: string } {
  let prev = GENESIS_PREV;
  for (let i = 0; i < chain.length; i++) {
    const r = chain[i];
    const expected = sha256(canonical({ seq: r.seq, ts: r.ts, actor: r.actor, op: r.op, target: r.target, ok: r.ok, sha256: r.sha256, prevHash: r.prevHash }));
    if (r.prevHash !== prev || r.hash !== expected) {
      return { valid: false, checked: i, firstBadIndex: i, root: prev, merkleRoot: merkleRoot(chain.map((x) => x.hash)) };
    }
    prev = r.hash;
  }
  return { valid: true, checked: chain.length, firstBadIndex: -1, root: prev, merkleRoot: merkleRoot(chain.map((x) => x.hash)) };
}

// load persisted chain (survives restarts)
