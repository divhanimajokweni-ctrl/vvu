function json(res: ServerResponse, status: number, body: unknown) {
  const s = JSON.stringify(body);
  res.writeHead(status, { 'Content-Type': 'application/json', 'Cache-Control': 'no-store' });
  res.end(s);
}

async function readBody(req: IncomingMessage): Promise<Record<string, unknown>> {
  const chunks: Buffer[] = [];
  for await (const c of req) chunks.push(c as Buffer);
  if (chunks.length === 0) return {};
  try {
    return JSON.parse(Buffer.concat(chunks).toString('utf8'));
  } catch {
    return {};
  }
}

function statusSnapshot() {
  return {
    ok: true,
    node: NODE_ID,
    protocol: PROTOCOL_ID,
    agentOnline: agent.online(),
    agent: agent.deviceId ? { deviceId: agent.deviceId, name: fieldDevices.get(agent.deviceId)?.name ?? 'unknown', lastSeenAgoMs: Date.now() - agent.lastSeen } : null,
    pairedDevices: fieldDevices.size,
    viewerCount,
    pairing: { active: [...pendingPairing.values()].some((p) => p.expiresAt > Date.now()) },
    receipts: { count: receipts.length, root: receipts.length ? receipts[receipts.length - 1].hash : GENESIS_PREV, verified: verifyChain(receipts).valid, merkleRoot: merkleRoot(receipts.map((r) => r.hash)), anchor: 'NOT WIRED — tier/anchor is :3004-only (Task 39 scope)' },
    integrity: { runningHash: RUNNING_HASH, bootTs: BOOT_TS },
  };
}

